#!/usr/bin/env python3
"""Turn the Bocchi pet sprite sheet into lens frames for the glasses.

    python3 scripts/build-bocchi-sprite.py [assets/bocchi/spritesheet.webp]

Needs Pillow. Writes glasses/src/ui/bocchi-frames.ts: per assistant state, the chosen frames of one
sheet row as 160x144 images with levels 0..15, packed two pixels a byte (high nibble first), deflated
(zlib) and base64'd. The glasses inflate them at start-up (DecompressionStream).

The lens is green on see-through black, so the cartoon is drawn as lit line art: dark outlines and
features glow (15), the mouth and mid tones are mid (11), and the light pink/skin fills stay dim (2-5),
so her face reads at a glance and few pixels are bright. Large dark areas (the skirt) stay dim with a
lit edge instead of becoming a solid bright block. See assets/bocchi/CREDITS.md for the artwork.
"""

import base64
import os
import sys
import zlib

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "assets", "bocchi", "spritesheet.webp")
OUT = os.path.join(ROOT, "glasses", "src", "ui", "bocchi-frames.ts")

CW, CH = 192, 208  # pet sheet cells
CROP = (4, 4, 188, 190)  # inside a cell: her whole silhouette, feet trimmed a little
TW, TH = 160, 144  # the lens tile

# state: (sheet row, frames of that row to keep)
STATES = {
    "idle": (0, [0, 1, 2, 3, 4, 5]),
    "listening": (6, [0, 1, 2, 3, 4, 5]),
    "thinking": (8, [0, 1, 2, 3, 4, 5]),
    "working": (7, [0, 1, 2, 3, 4, 5]),
    "talking": (4, [0, 1, 2, 3, 4]),
    "failed": (5, [1, 3, 4, 6]),
}


def level(l: float) -> int:
    if l < 0.45:
        return 11
    if l < 0.62:
        return 5
    if l < 0.80:
        return 3
    return 2 if l < 0.97 else 6  # eye whites and highlights a touch brighter than skin


def frame(sheet: Image.Image, row: int, col: int) -> bytes:
    cell = sheet.crop((col * CW + CROP[0], row * CH + CROP[1], col * CW + CROP[2], row * CH + CROP[3]))
    s = min(TW / cell.width, TH / cell.height)
    cell = cell.resize((round(cell.width * s), round(cell.height * s)), Image.LANCZOS)
    w, h = cell.size
    px = cell.load()
    lum = [[None] * w for _ in range(h)]
    for y in range(h):
        for x in range(w):
            r, g, b, a = px[x, y]
            lum[y][x] = None if a < 100 else (0.299 * r + 0.587 * g + 0.114 * b) / 255

    def dark(x: int, y: int) -> bool:
        return 0 <= x < w and 0 <= y < h and lum[y][x] is not None and lum[y][x] < 0.30

    out = bytearray(TW * TH)
    ox, oy = (TW - w) // 2, TH - h
    for y in range(h):
        for x in range(w):
            l = lum[y][x]
            if l is None:
                continue
            if l < 0.30:
                inner = all(dark(x + dx, y + dy) for dx in (-2, 0, 2) for dy in (-2, 0, 2))
                v = 4 if inner else 15
            else:
                v = level(l)
            out[(oy + y) * TW + ox + x] = v
    return bytes(out)


def pack(px: bytes) -> str:
    packed = bytes((px[i] << 4) | px[i + 1] for i in range(0, len(px), 2))
    return base64.b64encode(zlib.compress(packed, 9)).decode("ascii")


def main() -> None:
    sheet = Image.open(SRC).convert("RGBA")
    if sheet.size not in ((1536, 1872), (1536, 2288)):
        sys.exit(f"{SRC}: {sheet.size} is not a pet sheet (1536x1872 or 1536x2288)")
    lines = [
        "// Generated by scripts/build-bocchi-sprite.py from assets/bocchi/spritesheet.webp: do not edit.",
        '// Artwork: "Bocchi" Codex pet by salma s. (petdex.dev/pets/momo-4); see assets/bocchi/CREDITS.md.',
        "// Each frame: 160x144 levels 0..15, two pixels a byte (high nibble first), zlib-deflated, base64.",
        "",
        f"export const BOCCHI_W = {TW};",
        f"export const BOCCHI_H = {TH};",
        "",
        "export const BOCCHI_FRAMES = {",
    ]
    total = 0
    for state, (row, cols) in STATES.items():
        lines.append(f"  {state}: [")
        for c in cols:
            b64 = pack(frame(sheet, row, c))
            total += len(b64)
            lines.append(f'    "{b64}",')
        lines.append("  ],")
    lines.append("};")
    with open(OUT, "w") as f:
        f.write("\n".join(lines) + "\n")
    n = sum(len(c) for _, c in STATES.values())
    print(f"{OUT}: {n} frames, {total // 1024} KB of base64")


if __name__ == "__main__":
    main()
