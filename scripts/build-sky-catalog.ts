// Builds src/hub/sky/catalog.ts from the Yale Bright Star Catalogue, 5th revised edition (Hoffleit &
// Warren 1991, CDS VizieR V/50, file "catalog", fixed-width): every star to V 4.5, plus the fainter
// ones the constellation figures (src/hub/sky/figures.ts) use. J2000 positions, magnitude and Bayer
// designation only, so the bundled file stays ~30 KB.
//   curl -O https://cdsarc.cds.unistra.fr/ftp/V/50/catalog.gz && gunzip catalog.gz
//   node --import tsx scripts/build-sky-catalog.ts <path to catalog>

import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { FIGURES } from "../src/hub/sky/figures.js";

const MAG = 4.5;
const src = process.argv[2];
if (!src) throw new Error("usage: build-sky-catalog.ts <BSC5 catalog file>");

type Row = { ra: number; dec: number; mag: number; key: string };
const rows: Row[] = [];
for (const line of readFileSync(src, "latin1").split("\n")) {
  if (line.length < 107 || !line.slice(75, 77).trim()) continue; // removed entries have no position
  const ra = (Number(line.slice(75, 77)) + Number(line.slice(77, 79)) / 60 + Number(line.slice(79, 83)) / 3600) * 15;
  const dec = (line[83] === "-" ? -1 : 1) * (Number(line.slice(84, 86)) + Number(line.slice(86, 88)) / 60 + Number(line.slice(88, 90)) / 3600);
  const mag = Number(line.slice(102, 107));
  if (!Number.isFinite(ra) || !Number.isFinite(dec) || !Number.isFinite(mag)) continue;
  // Name bytes 5-14: Flamsteed (5-7), Bayer (8-10), component digit (11), constellation (12-14)
  const bayer = line.slice(7, 10).trim().toLowerCase(), sup = line.slice(10, 11).trim(), con = line.slice(11, 14).trim();
  rows.push({ ra, dec, mag, key: bayer && con ? `${bayer}${sup} ${con}` : "" });
}

// stars the figures need, whatever their magnitude
const need = new Set<string>();
for (const [con, f] of Object.entries(FIGURES))
  for (const chain of f.lines.split(" "))
    for (const tok of chain.split("-")) {
      const [b, c] = tok.split(".");
      need.add(`${b} ${c ?? con}`);
    }
const bare = (k: string) => k.replace(/\d(?= )/, "");
const brightestOf = new Map<string, Row>();
for (const r of rows) if (r.key && (!brightestOf.has(bare(r.key)) || brightestOf.get(bare(r.key))!.mag > r.mag)) brightestOf.set(bare(r.key), r);

const keep = rows.filter((r) => r.mag <= MAG || (r.key && (need.has(r.key) || (need.has(bare(r.key)) && brightestOf.get(bare(r.key)) === r))));
const missing = [...need].filter((k) => !keep.some((r) => r.key === k || (bare(r.key) === k && brightestOf.get(k) === r)));
if (missing.length) throw new Error(`figure stars not in the catalogue: ${missing.join(", ")}`);
keep.sort((a, b) => a.mag - b.mag);

const body = keep.map((r) => `${r.ra.toFixed(3)} ${r.dec.toFixed(3)} ${r.mag.toFixed(2)}${r.key ? ` ${r.key.replace(" ", "_")}` : ""}`).join("\n");
const out = `// Generated by scripts/build-sky-catalog.ts: do not edit.
// Source: Yale Bright Star Catalogue, 5th revised ed. (Hoffleit & Warren 1991), CDS VizieR V/50.
// ${keep.length} stars (V <= ${MAG}, plus the figures' fainter stars), brightest first.
// Per line: RA J2000 (deg), Dec J2000 (deg), V mag, Bayer designation ("alp1_Cen") if any.
export const CATALOG = \`
${body}
\`;
`;
const dst = join(import.meta.dirname, "../src/hub/sky/catalog.ts");
writeFileSync(dst, out);
console.log(`${keep.length} stars, ${(out.length / 1024).toFixed(1)} KB -> ${dst}`);
